#!/usr/bin/env python3
"""Generate the GitHub Pages site and the LaTeX QR snippet for the thesis videos.

Edit VIDEOS below (titles, descriptions), then run:  python3 build.py
"""
import html
from pathlib import Path

BASE_URL = "https://edforti.github.io/thesis-video"
SITE_TITLE = "PhD Thesis - Supplementary videos"
AUTHOR = "Edoardo Forti"

# slug -> URL path (keep it short: shorter URL = simpler, more readable QR code)
VIDEOS = [
    {"slug": "npr5-jrm", "file": "NPR5_JRM.mp4",
     "title": "NPR5 - JRM", "description": ""},
    {"slug": "npr7-jsm", "file": "NPR7_JSM.mp4",
     "title": "NPR7 - JSM", "description": ""},
    {"slug": "sandia-a", "file": "T_sandia_A.mp4",
     "title": "Sandia flame A - temperature field", "description": ""},
    {"slug": "cavity", "file": "T_cavity_fixed.mp4",
     "title": "Cavity - temperature field", "description": ""},
    {"slug": "sphere", "file": "sphere_T_field_profile_zoom.mp4",
     "title": "Sphere - temperature field profile (zoom)", "description": ""},
    {"slug": "layer-evolution", "file": "compare_layer_evolution.mp4",
     "title": "Layer evolution comparison", "description": ""},
]

CSS = """
:root{--bg:#fafaf8;--fg:#1d1d1f;--muted:#6b6b70;--line:#e2e2de;--accent:#1f5fa8}
@media (prefers-color-scheme:dark){:root{--bg:#141416;--fg:#ececee;--muted:#9a9aa2;--line:#2c2c30;--accent:#7fb0ec}}
*{box-sizing:border-box}
body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.55 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}
main{max-width:960px;margin:0 auto;padding:24px 16px 48px}
header p,.desc,footer{color:var(--muted)}
h1{font-size:1.5rem;margin:.2em 0 .3em;line-height:1.25}
a{color:var(--accent)}
video{width:100%;height:auto;background:#000;border-radius:6px;display:block}
.desc{margin:1em 0}
ul{list-style:none;padding:0;display:grid;gap:16px;grid-template-columns:repeat(auto-fill,minmax(260px,1fr))}
li a{display:block;text-decoration:none;color:var(--fg);border:1px solid var(--line);border-radius:8px;overflow:hidden}
li img{width:100%;display:block;aspect-ratio:16/9;object-fit:cover;background:#000}
li span{display:block;padding:10px 12px;font-weight:500}
footer{margin-top:32px;font-size:.85rem;border-top:1px solid var(--line);padding-top:12px}
"""


def page(title, body, depth):
    up = "../" * depth
    return f"""<!doctype html>
<html lang="en"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title>
<link rel="stylesheet" href="{up}style.css">
</head><body><main>
{body}
<footer>{html.escape(AUTHOR)} - PhD thesis, Sapienza Università di Roma</footer>
</main></body></html>
"""


def main():
    root = Path(__file__).parent
    (root / "style.css").write_text(CSS.lstrip())
    (root / ".nojekyll").write_text("")

    for v in VIDEOS:
        assert (root / "videos" / v["file"]).exists(), v["file"]
        stem = v["file"].rsplit(".", 1)[0]
        desc = f'<p class="desc">{html.escape(v["description"])}</p>' if v["description"] else ""
        body = f"""<header><p><a href="../">&larr; All videos</a></p>
<h1>{html.escape(v["title"])}</h1></header>
<video controls playsinline preload="metadata" poster="../videos/{stem}.jpg">
  <source src="../videos/{v["file"]}" type="video/mp4">
  <a href="../videos/{v["file"]}">Download the video</a>
</video>
{desc}
<p><a href="../videos/{v["file"]}" download>Download MP4</a></p>"""
        d = root / v["slug"]
        d.mkdir(exist_ok=True)
        (d / "index.html").write_text(page(v["title"], body, 1))

    items = "\n".join(
        f'<li><a href="{v["slug"]}/"><img src="videos/{v["file"].rsplit(".", 1)[0]}.jpg" alt="" loading="lazy">'
        f'<span>{html.escape(v["title"])}</span></a></li>' for v in VIDEOS)
    body = f"<header><h1>{html.escape(SITE_TITLE)}</h1><p>{html.escape(AUTHOR)}</p></header>\n<ul>\n{items}\n</ul>"
    (root / "index.html").write_text(page(SITE_TITLE, body, 0))

    # LaTeX snippet to upload to Overleaf
    tex = ["% Generated by build.py - QR codes for the thesis videos",
           "% Requires in the preamble: \\usepackage{qrcode} and \\usepackage{hyperref}",
           f"\\newcommand{{\\thesisvideobase}}{{{BASE_URL}}}",
           "% \\thesisvideo{<slug>}{<caption>}: QR code + clickable link",
           "\\newcommand{\\thesisvideo}[2]{%",
           "  \\begin{tabular}{c}",
           "    \\qrcode[height=2.2cm,level=M,nolink]{\\thesisvideobase/#1/}\\\\[6pt]",
           "    \\footnotesize\\hypersetup{pdfborder={0 0 0}}\\href{\\thesisvideobase/#1/}{#2}",
           "  \\end{tabular}}",
           "",
           "% Available videos:"]
    tex += [f"%   \\thesisvideo{{{v['slug']}}}{{{v['title']}}}" for v in VIDEOS]
    (root / "latex" ).mkdir(exist_ok=True)
    (root / "latex" / "thesis_videos.tex").write_text("\n".join(tex) + "\n")
    print("Built", len(VIDEOS), "video pages")


if __name__ == "__main__":
    main()
